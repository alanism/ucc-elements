"""Vertical native Chromium/WebAudio DJ behavior slices; no audio mocks."""
import unittest
from pathlib import Path
from playwright.sync_api import sync_playwright
from tests.transport_native import NATIVE_AUDIT
ROOT=Path(__file__).resolve().parents[1]
class DJBehaviorTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.p=sync_playwright().start();cls.browser=cls.p.chromium.launch()
    @classmethod
    def tearDownClass(cls):
        cls.browser.close();cls.p.stop()
    def setUp(self):
        self.page=self.browser.new_page(viewport={'width':1440,'height':1000})
        self.errors=[];self.page.on('pageerror',lambda e:self.errors.append(str(e)))
        self.page.add_init_script(NATIVE_AUDIT)
        self.page.goto((ROOT/'dj-decks'/'index.html').as_uri())
    def tearDown(self):
        self.page.close();self.assertEqual(self.errors,[])
    def play(self,i=1):
        self.page.locator(f'#play-{i}').click()
        self.page.wait_for_function(f'window.djLab && djLab.decks[{i-1}].playing')
    def test_native_transport_pause_resume_cue_and_safety(self):
        self.assertTrue(self.page.evaluate('!!window.djLab && djLab.ctx===null'),'Arrival must expose silent diagnostics without allocating an AudioContext')
        self.play()
        self.assertTrue(self.page.evaluate('djLab.ctx instanceof AudioContext && djLab.decks[0].source instanceof AudioBufferSourceNode && djLab.decks[0].source.loop && djLab.decks[0].buffer.duration===8'))
        self.page.wait_for_timeout(120)
        self.page.locator('#play-1').click()
        offset=self.page.evaluate('djLab.decks[0].offset')
        self.assertGreater(offset,0.05)
        self.assertTrue(self.page.evaluate('!djLab.decks[0].source && !djLab.decks[0].playing'))
        self.play()
        self.assertGreaterEqual(self.page.evaluate('djLab.decks[0].position()'),offset)
        self.page.locator('#cue-1').click()
        self.assertEqual(self.page.evaluate('djLab.decks[0].offset'),0)
        self.play(2)
        self.page.evaluate("window.dispatchEvent(new Event('blur'))")
        self.page.wait_for_function('djLab.ctx===null')
        self.assertTrue(self.page.evaluate('djLab.decks.every(d=>!d.playing&&!d.source&&!d.wanted) && djLab.samplers.size===0'))
        self.page.evaluate("window.dispatchEvent(new Event('focus'))")
        self.assertTrue(self.page.evaluate('djLab.ctx===null'))
    def test_native_tempo_seek_sync_and_pointer_ownership(self):
        self.play()
        self.page.locator('#tempo-1').focus();self.page.keyboard.press('End')
        self.assertAlmostEqual(self.page.evaluate('djLab.decks[0].source.playbackRate.value'),1.08,places=4)
        self.assertIn('129.6 BPM',self.page.locator('#status-1').inner_text())
        self.page.locator('#jog-1').focus();self.page.keyboard.press('Home')
        self.page.wait_for_function('djLab.decks[0].playing')
        self.assertLess(self.page.evaluate('djLab.decks[0].position()'),0.15)
        self.page.keyboard.press('PageUp');self.page.wait_for_function('djLab.decks[0].playing')
        self.assertGreater(self.page.evaluate('djLab.decks[0].position()'),0.9)
        self.play(2);self.page.locator('#sync-2').click()
        self.page.wait_for_function('djLab.decks[1].playing')
        self.assertAlmostEqual(self.page.evaluate('djLab.decks[1].base*djLab.decks[1].source.playbackRate.value'),129.6,places=3)
        self.assertEqual(self.page.evaluate('__audioAudit.snapshot().active'),2)
        self.page.locator('#tempo-1').focus();self.page.keyboard.press('Home')
        self.assertAlmostEqual(self.page.evaluate('djLab.decks[0].source.playbackRate.value'),.92,places=4)
        self.page.locator('#tempo-1').dblclick()
        self.assertEqual(self.page.locator('#tempo-1').get_attribute('aria-valuenow'),'0')
        self.page.evaluate("""(()=>{const el=document.getElementById('tempo-1');el.dispatchEvent(new PointerEvent('pointerdown',{pointerId:77,button:0,clientY:100,bubbles:true}));el.dispatchEvent(new PointerEvent('pointermove',{pointerId:78,clientY:0,bubbles:true}));el.dispatchEvent(new PointerEvent('pointercancel',{pointerId:77,bubbles:true}));el.dispatchEvent(new PointerEvent('pointermove',{pointerId:77,clientY:0,bubbles:true}));})()""")
        self.assertEqual(self.page.locator('#tempo-1').get_attribute('aria-valuenow'),'0')
    def test_native_eq_cfx_gain_law_and_preview_routes(self):
        self.play();self.play(2)
        self.assertTrue(self.page.evaluate('!!djLab.decks[0].filters && djLab.decks[0].filters.hi instanceof BiquadFilterNode'),'EQ must be native filters in the deck signal chain')
        for key,kind in [('hi','highshelf'),('mid','peaking'),('low','lowshelf')]:
            self.page.locator(f'#knob-1-{key}').focus();self.page.keyboard.press('End')
            self.assertEqual(self.page.evaluate(f'djLab.decks[0].filters.{key}.type'),kind)
            self.assertEqual(self.page.evaluate(f'djLab.decks[0].filters.{key}.gain.value'),12)
        self.page.locator('#knob-1-cfx').focus();self.page.keyboard.press('End')
        self.assertLess(self.page.evaluate('djLab.decks[0].filters.cfx.frequency.value'),100)
        self.page.locator('#fx-select').click()
        self.assertEqual(self.page.evaluate('djLab.decks[0].filters.cfx.type'),'highpass')
        self.page.locator('#gain-1').focus();self.page.keyboard.press('End')
        self.assertAlmostEqual(self.page.evaluate('djLab.decks[0].bus.gain.value'),2**-.5,places=5)
        self.page.locator('#smart').click()
        self.assertAlmostEqual(self.page.evaluate('djLab.decks[0].bus.gain.value'),.5,places=5)
        self.page.locator('#crossfader').focus();self.page.keyboard.press('End')
        self.assertEqual(self.page.evaluate('djLab.decks[0].bus.gain.value'),0)
        self.page.locator('#solo-1').click()
        self.assertEqual(self.page.evaluate('djLab.decks[0].bus.gain.value'),1)
        self.assertEqual(self.page.evaluate('djLab.decks[1].bus.gain.value'),0)
        self.assertEqual(self.page.locator('#solo-2').get_attribute('aria-pressed'),'false')
        self.page.locator('#solo-2').click()
        self.assertEqual(self.page.locator('#solo-1').get_attribute('aria-pressed'),'false')
        self.page.locator('#master').click()
        self.assertEqual(self.page.evaluate('djLab.route'),0)
        self.assertLessEqual(self.page.evaluate('djLab.master.gain.value'),.150001)
        self.assertEqual(self.page.evaluate('__audioAudit.snapshot().filters.length'),8)
    def test_hotcues_shift_and_native_sampler_cleanup(self):
        self.page.locator('[data-deck="1"][data-pad="2"]').click()
        self.assertEqual(self.page.evaluate('djLab.decks[0].offset'),4,'Hotcue 3 must recall the actual four-second source offset')
        self.page.wait_for_function('djLab.decks[0].playing')
        self.assertAlmostEqual(self.page.evaluate('__audioAudit.sources[0].offset'),4)
        self.page.locator('#play-1').click()
        self.page.locator('#jog-1').focus();self.page.keyboard.press('PageUp')
        self.page.locator('#shift-1').click()
        position=self.page.evaluate('djLab.decks[0].position()')
        self.page.locator('[data-deck="1"][data-pad="3"]').click()
        self.assertAlmostEqual(self.page.evaluate('djLab.decks[0].cues[3]'),position,places=3)
        self.page.locator('#shift-1').click()
        self.page.locator('[data-deck="1"][data-pad="3"]').click()
        self.page.wait_for_function('djLab.decks[0].playing')
        self.assertAlmostEqual(self.page.evaluate('djLab.decks[0].offset'),position,places=3)
        for i in range(4,8):
            self.page.locator(f'[data-deck="2"][data-pad="{i}"]').click()
        self.assertGreater(self.page.evaluate('__audioAudit.sources.filter(s=>s.started&&!s.node.loop).length'),3)
        self.assertTrue(self.page.evaluate('Array.from(djLab.samplers).every(s=>s instanceof AudioBufferSourceNode && s.buffer.duration<.5)'))
        self.page.wait_for_timeout(450)
        self.assertEqual(self.page.evaluate('djLab.samplers.size'),0)
        self.assertTrue(self.page.evaluate('__audioAudit.sources.filter(s=>!s.node.loop).every(s=>s.ended&&s.disconnected)'))
        self.page.locator('[data-deck="1"][data-pad="4"]').click()
        self.page.evaluate("window.dispatchEvent(new Event('blur'))")
        self.page.wait_for_function('__audioAudit.contexts.every(c=>c.state==="closed")')
        self.assertEqual(self.page.evaluate('__audioAudit.snapshot().active'),0)
        self.assertTrue(self.page.evaluate('__audioAudit.sources.every(s=>s.disconnected)'))
if __name__=='__main__':unittest.main()
